// Builds src/world/star-catalog.ts from d3-celestial's stars.6.json (Hipparcos, J2000, mag ≤ 6):
//   curl -sSfL -o stars.6.json https://cdn.jsdelivr.net/gh/ofrohn/d3-celestial@master/data/stars.6.json
//   node tools/build-stars.mjs stars.6.json
// Keeps the stars down to MAG_LIMIT, brightest first; each as RA deg, Dec deg, V mag, B-V.
import { readFileSync, writeFileSync } from 'node:fs';

const MAG_LIMIT = 5.5;
const src = process.argv[2];
if (!src) throw new Error('usage: node tools/build-stars.mjs <stars.6.json>');
const features = JSON.parse(readFileSync(src, 'utf8')).features;
const rows = features
  .filter((f) => f.properties.mag <= MAG_LIMIT)
  .sort((a, b) => a.properties.mag - b.properties.mag)
  .map((f) => {
    const [lon, dec] = f.geometry.coordinates;
    const ra = (lon + 360) % 360;
    const bv = Number.isFinite(parseFloat(f.properties.bv)) ? parseFloat(f.properties.bv) : 0.6;
    return [ra.toFixed(3), dec.toFixed(3), f.properties.mag.toFixed(2), bv.toFixed(2)].map(Number).join(',');
  });
const out = `// Generated by tools/build-stars.mjs from d3-celestial stars.6.json (Hipparcos, BSD-3-Clause).
// ${rows.length} stars to V ${MAG_LIMIT}, brightest first: RA deg, Dec deg (J2000), V mag, B-V.
export const STAR_CATALOG: readonly number[] = [
${rows.map((r) => `  ${r},`).join('\n')}
];
`;
writeFileSync(new URL('../src/world/star-catalog.ts', import.meta.url), out);
console.log(`${rows.length} stars`);
